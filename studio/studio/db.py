"""Accès à la base de l'Atelier SAPHYRA (PostgreSQL du VPS).

Le Studio ajoute trois tables à côté de ideas / tasks / journal :
  studio_projects : un projet par idée explorée, avec son étape dans le pipeline ;
  studio_events   : le fil de ce que chaque agent a fait (et pourquoi) ;
  studio_usage    : tokens et coût par appel, pour tenir les plafonds.
Une maquette livrée devient une fiche normale de l'Atelier (table ideas).
"""
import json
import os
from datetime import date
from pathlib import Path

import psycopg
from psycopg.rows import dict_row

from . import config

# Étapes du pipeline, dans l'ordre. « tuee » et « livree » sont terminales.
STAGES = ["nouvelle", "architecture", "dev", "revue", "marche", "doc", "prete"]
TERMINAL = ["livree", "tuee", "bloquee"]
LABELS = {
    "nouvelle": "Panel métier", "architecture": "Architecture",
    "dev": "Maquette", "revue": "Revue du POC", "doc": "Documentation",
    "marche": "Vendabilité", "prete": "Prête", "livree": "Livrée", "tuee": "Cimetière", "bloquee": "Bloquée (technique)",
}

SCHEMA = """
CREATE TABLE IF NOT EXISTS studio_projects (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug        text UNIQUE NOT NULL,
  title       text NOT NULL,
  domain      text NOT NULL DEFAULT '',
  stage       text NOT NULL DEFAULT 'nouvelle',
  brief       jsonb NOT NULL DEFAULT '{}',   -- idée structurée (Éclaireur)
  panel       jsonb NOT NULL DEFAULT '{}',   -- avis du panel métier (porte 1)
  archi       jsonb NOT NULL DEFAULT '{}',   -- architecture clean core
  test        jsonb NOT NULL DEFAULT '{}',   -- dernier rapport du testeur
  revue       jsonb NOT NULL DEFAULT '{}',   -- revue du POC (porte 2)
  doc_md      text  NOT NULL DEFAULT '',
  market      jsonb NOT NULL DEFAULT '{}',   -- vendabilité (porte 3)
  score       numeric(3,2),
  dev_loops   integer NOT NULL DEFAULT 0,
  corrections integer NOT NULL DEFAULT 0,
  kill_reason text,
  idea_id     uuid,                          -- fiche de l'Atelier une fois livrée
  cost_usd    numeric(8,4) NOT NULL DEFAULT 0,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  ready_at    timestamptz,
  delivered_at timestamptz
);
CREATE INDEX IF NOT EXISTS studio_projects_stage_idx ON studio_projects(stage);
CREATE TABLE IF NOT EXISTS studio_events (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  project_id integer REFERENCES studio_projects(id) ON DELETE CASCADE,
  ts         timestamptz NOT NULL DEFAULT now(),
  agent      text NOT NULL,
  kind       text NOT NULL,        -- info | go | kill | erreur | budget
  summary    text NOT NULL
);
CREATE INDEX IF NOT EXISTS studio_events_ts_idx ON studio_events(ts DESC);
CREATE TABLE IF NOT EXISTS studio_usage (
  id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts         timestamptz NOT NULL DEFAULT now(),
  project_id integer,
  agent      text NOT NULL,
  model      text NOT NULL,
  input_tokens  integer NOT NULL,
  output_tokens integer NOT NULL,
  searches   integer NOT NULL DEFAULT 0,
  cost_usd   numeric(8,4) NOT NULL
);
CREATE TABLE IF NOT EXISTS studio_state (k text PRIMARY KEY, v text);
ALTER TABLE studio_projects ADD COLUMN IF NOT EXISTS blocked_stage text;
-- Une erreur technique n'est pas un jugement : les idées tuées ainsi (avant le 10/11/2026) repartent au panel.
UPDATE studio_projects SET stage = 'nouvelle', kill_reason = NULL
 WHERE stage = 'tuee' AND kill_reason LIKE '%Erreur technique répétée%';
-- Faux refus de l'architecte fabriqués par la réparation JSON à partir d'une réponse vide (10/11/2026).
UPDATE studio_projects SET stage = 'architecture', kill_reason = NULL
 WHERE stage = 'tuee' AND kill_reason LIKE '[architecte]%' AND kill_reason LIKE '%convertir%';
"""


def dsn() -> str:
    if os.environ.get("DATABASE_URL"):
        return os.environ["DATABASE_URL"]
    pw = Path(os.environ.get("SECRETS_DIR", "/secrets"), "pg_password").read_text().strip()
    host = os.environ.get("DB_HOST", "db")
    return f"postgresql://saphyra:{pw}@{host}:5432/saphyra"


def conn():
    return psycopg.connect(dsn(), row_factory=dict_row, autocommit=True)


def migrate():
    with conn() as c:
        c.execute(SCHEMA)


def q(sql, *args):
    with conn() as c:
        cur = c.execute(sql, args)
        return cur.fetchall() if cur.description else []


def q1(sql, *args):
    r = q(sql, *args)
    return r[0] if r else None


# ---------- Projets ----------
def project(pid):
    return q1("SELECT * FROM studio_projects WHERE id=%s", pid)


def update(pid, **fields):
    if not fields:
        return
    cols, vals = [], []
    for k, v in fields.items():
        cols.append(f"{k}=%s")
        vals.append(json.dumps(v, ensure_ascii=False) if isinstance(v, (dict, list)) else v)
    q(f"UPDATE studio_projects SET {', '.join(cols)}, updated_at=now() WHERE id=%s", *vals, pid)


def event(pid, agent, kind, summary):
    q("INSERT INTO studio_events(project_id, agent, kind, summary) VALUES(%s,%s,%s,%s)",
      pid, agent, kind, summary[:2000])


def active_projects():
    return q("SELECT * FROM studio_projects WHERE stage <> ALL(%s) ORDER BY id", TERMINAL)


def next_project():
    """Le projet le plus avancé passe d'abord : on finit avant de commencer."""
    order = " ".join(f"WHEN '{s}' THEN {i}" for i, s in enumerate(STAGES))
    return q1(f"""SELECT * FROM studio_projects WHERE stage <> ALL(%s) AND stage <> 'prete'
                  ORDER BY CASE stage {order} END DESC, id LIMIT 1""", TERMINAL)


def relaunch(pid):
    q("""UPDATE studio_projects SET stage = coalesce(blocked_stage, 'nouvelle'), blocked_stage = NULL, kill_reason = NULL,
         updated_at = now() WHERE id = %s AND stage = 'bloquee'""", pid)
    event(pid, "andre", "info", "Relancé depuis le tableau de bord.")


# ---------- Budget ----------
def spent_today():
    r = q1("SELECT coalesce(sum(cost_usd),0) s FROM studio_usage WHERE ts >= date_trunc('day', now() AT TIME ZONE %s) AT TIME ZONE %s",
           str(config.TZ), str(config.TZ))
    return float(r["s"])


def record_usage(pid, agent, model, tin, tout, searches, cost):
    q("INSERT INTO studio_usage(project_id, agent, model, input_tokens, output_tokens, searches, cost_usd) VALUES(%s,%s,%s,%s,%s,%s,%s)",
      pid, agent, model, tin, tout, searches, cost)
    if pid:
        q("UPDATE studio_projects SET cost_usd = cost_usd + %s WHERE id=%s", cost, pid)


def ready_today():
    r = q1("""SELECT count(*) n FROM studio_projects WHERE ready_at >= date_trunc('day', now() AT TIME ZONE %s) AT TIME ZONE %s""",
           str(config.TZ), str(config.TZ))
    return r["n"]


def state(k, v=None):
    if v is None:
        r = q1("SELECT v FROM studio_state WHERE k=%s", k)
        return r["v"] if r else None
    q("INSERT INTO studio_state(k,v) VALUES(%s,%s) ON CONFLICT (k) DO UPDATE SET v=excluded.v", k, v)


# ---------- Contexte pour l'Éclaireur ----------
def known_titles():
    """Tout ce qui existe déjà : fiches de l'Atelier + projets du Studio (y compris tués)."""
    ideas = q("SELECT title, pitch FROM ideas ORDER BY created_at DESC LIMIT 200")
    studio = q("SELECT title, stage, kill_reason FROM studio_projects ORDER BY id DESC LIMIT 300")
    return ideas, studio


# ---------- Livraison dans l'Atelier ----------
def deliver_to_atelier(p, urls):
    b = p["brief"] or {}
    m = p["market"] or {}
    today = date.today().isoformat()
    tasks = ["Revoir la maquette et la documentation",
             "Décider : montrer à un client, approfondir ou abandonner"]
    notes = (f"Maquette produite par le Studio IA.\n\n- Maquette : {urls['maquette']}\n- Documentation : {urls['doc']}\n"
             f"- Score de vendabilité : {p['score']}/5\n- Coût de production : {float(p['cost_usd']):.2f} $")
    body = ("## Notes\n" + notes + "\n\n## Plan d'action\n" + "\n".join(f"- [ ] {t}" for t in tasks) +
            f"\n\n## Journal\n- **{today}** — Livrée par le Studio IA après panel métier, revue du POC et évaluation commerciale.\n")
    scores = m.get("scores", {})
    clamp = lambda v: max(1, min(5, round(float(v)))) if v not in (None, "") else None
    with conn() as c, c.transaction():
        row = c.execute("""INSERT INTO ideas(title, stage, type, priority, owner, tags, pitch, problem, target, value, business,
                             next_step, valeur, effort, confiance, progress, body_md)
                           VALUES(%s,'POC','Appli SAP','P2','Studio IA',%s,%s,%s,%s,%s,%s,%s,%s,%s,%s,0.3,%s) RETURNING id""",
                        (p["title"], ["Studio IA", "IA", "Clean core", "Fiori"] + ([p["domain"]] if p["domain"] else []),
                         b.get("pitch", ""), b.get("probleme", ""), b.get("cible", ""), b.get("valeur", ""),
                         m.get("modele_economique", ""), "Revoir la maquette",
                         clamp(scores.get("valeur")), clamp(scores.get("effort")), clamp(scores.get("confiance")), body)).fetchone()
        iid = row["id"]
        for i, t in enumerate(tasks):
            c.execute("INSERT INTO tasks(idea_id, position, text, done) VALUES(%s,%s,%s,false)", (iid, i, t))
        c.execute("INSERT INTO journal(idea_id, position, entry_date, text) VALUES(%s,0,%s,%s)",
                  (iid, today, "Livrée par le Studio IA après panel métier, revue du POC et évaluation commerciale."))
        c.execute("UPDATE studio_projects SET stage='livree', idea_id=%s, delivered_at=now(), updated_at=now() WHERE id=%s",
                  (iid, p["id"]))
    return iid
