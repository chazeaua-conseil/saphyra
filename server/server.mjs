// items : [{ref, notion_url, created, updated, title, ...champs, body}]. Les fiches dont notion_url existe déjà sont ignorées.
const htmlToMd = s => String(s || "")
  .replace(/<b>(.*?)<\/b>/g, "**$1**").replace(/<i>(.*?)<\/i>/g, "*$1*").replace(/<code>(.*?)<\/code>/g, "`$1`")
  .replace(/^\s*<p \/>\s*$/gm, "").replace(/<empty-block\/>/g, "");
async function importIdeas(items) {
  if (!Array.isArray(items)) throw new Error("items doit être un tableau");
  return tx(async c => {
    const done = [], skipped = [];
    for (const it of items) {
      if (it.notion_url && (await c.query("SELECT 1 FROM ideas WHERE notion_url=$1", [it.notion_url])).rowCount) { skipped.push(it.notion_url); continue; }
      const cols = ["notion_url", "created_at", "updated_at", "body_md"], body = htmlToMd(it.body);
      const vals = [it.notion_url || null, it.created || new Date().toISOString(), it.updated || new Date().toISOString(), body];
      if (it.ref !== undefined) { cols.push("ref"); vals.push(Number(it.ref)); }
      for (const [k, col] of Object.entries(FIELDS)) if (it[k] !== undefined) { cols.push(col); vals.push(normField(k, it[k])); }
      const { rows: r } = await c.query(`INSERT INTO ideas(${cols.join(",")}) VALUES(${vals.map((_, i) => "$" + (i + 1)).join(",")}) RETURNING id, ref`, vals);
      await syncChildren(c, r[0].id, body);
      done.push("IDEE-" + r[0].ref);
    }
    await c.query("SELECT setval(pg_get_serial_sequence('ideas','ref'), GREATEST((SELECT max(ref) FROM ideas), 1))");
    return { imported: done, skipped };
  });
}

