  const url = new URL(req.url, "http://x");
  if (url.pathname === BASE + "/health") {
    try { const { rows } = await pool.query("SELECT count(*)::int AS ideas, (SELECT count(*)::int FROM tasks) AS tasks FROM ideas"); return send(res, 200, { ok: true, ...rows[0] }); }
    catch { return send(res, 503, { ok: false }); }
  }
  if (url.pathname !== `${BASE}/${TOKEN}/mcp`) return send(res, 404, { error: "not found" });
  if (req.method === "GET" || req.method === "DELETE") return send(res, 405, { error: "method not allowed" }, { Allow: "POST" });
  if (req.method !== "POST") return send(res, 405, { error: "method not allowed" }, { Allow: "POST" });
  let raw = ""; for await (const ch of req) { raw += ch; if (raw.length > 2_000_000) return send(res, 413, { error: "too large" }); }
  let msg; try { msg = JSON.parse(raw); } catch { return send(res, 400, { jsonrpc: "2.0", id: null, error: { code: -32700, message: "Parse error" } }); }
