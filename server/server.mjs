/* ---------------- Corps de fiche (même format que l'Atelier) ---------------- */
const DATE_RE = /\s*<date\s+start="(\d{4}-\d{2}-\d{2})"[^>]*\/?>(?:<\/date>)?/;
const KNOWN = { "notes": "notes", "plan d'action": "plan", "plan d’action": "plan", "plan": "plan", "journal": "journal" };
const isoDate = s => /^\d{4}-\d{2}-\d{2}$/.test(String(s || "").trim()) ? String(s).trim() : null;

function parseBody(md) {
  const b = { pre: [], order: [], raw: {}, notes: "", tasks: [], journal: [], planExtra: [], journalExtra: [] };
  let cur = null, buf = [];
  const close = () => {
    if (cur === null) b.pre = buf;
    else {
      const key = KNOWN[cur.toLowerCase().trim()];
      if (key === "notes") { b.notes = buf.join("\n").trim(); b.order.push("notes"); }
      else if (key === "plan") {
        b.order.push("plan");
        for (const l of buf) {
          const t = l.match(/^\s*- \[( |x|X)\]\s?(.*)$/);
          if (t) { const m = t[2].match(DATE_RE); b.tasks.push({ done: t[1].toLowerCase() === "x", text: m ? t[2].replace(DATE_RE, "").trim() : t[2], due: m ? m[1] : "" }); }
          else if (l.trim()) b.planExtra.push(l);
        }
      } else if (key === "journal") {
        b.order.push("journal");
        for (const l of buf) {
          const j = l.match(/^\s*-\s+(.*)$/);
          if (j) { const d = j[1].match(/^(?:<b>|\*\*)([^<*]+)(?:<\/b>|\*\*)\s*[—–-]\s*(.*)$/); b.journal.push(d ? { date: d[1].trim(), text: d[2] } : { date: "", text: j[1] }); }
          else if (l.trim()) b.journalExtra.push(l);
        }
      } else { const id = "raw:" + b.order.length; b.order.push(id); b.raw[id] = { title: cur, lines: buf }; }
    }
    buf = [];
  };
  for (const l of String(md || "").split("\n")) { const h = l.match(/^##\s+(.+?)\s*$/); if (h) { close(); cur = h[1]; } else buf.push(l); }
  close();
  for (const k of ["notes", "plan", "journal"]) if (!b.order.includes(k)) b.order.push(k);
  return b;
}
function buildBody(b) {
  const out = [];
  const pre = b.pre.join("\n").trim(); if (pre) out.push(pre);
  for (const k of b.order) {
    if (k === "notes") out.push("## Notes\n" + (b.notes.trim() || ""));
    else if (k === "plan") out.push("## Plan d'action\n" + [...b.tasks.map(t => `- [${t.done ? "x" : " "}] ${String(t.text).replace(/\n/g, " ")}${t.due ? ` <date start="${t.due}" />` : ""}`), ...b.planExtra].join("\n"));
    else if (k === "journal") out.push("## Journal\n" + [...b.journal.map(j => j.date ? `- **${j.date}** — ${j.text}` : `- ${j.text}`), ...b.journalExtra].join("\n"));
    else { const r = b.raw[k]; out.push("## " + r.title + "\n" + r.lines.join("\n").trim()); }
  }
  return out.join("\n\n").replace(/\n{3,}/g, "\n\n").trim() + "\n";
}

