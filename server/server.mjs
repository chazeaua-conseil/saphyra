const FIELDS = { title: "title", stage: "stage", type: "type", priority: "priority", owner: "owner", tags: "tags", pitch: "pitch", problem: "problem",
  target: "target", value: "value", business: "business", nextStep: "next_step", due: "due", valeur: "valeur", effort: "effort", confiance: "confiance", progress: "progress" };
const TEXTS = ["pitch", "problem", "target", "value", "business", "nextStep"];

function normField(k, v) {
  if (["valeur", "effort", "confiance"].includes(k)) { if (v === null || v === "" || v === undefined) return null; const n = Math.round(Number(v)); if (!(n >= 1 && n <= 5)) throw new Error(`${k} doit être entre 1 et 5`); return n; }
  if (k === "progress") { const n = Number(v); if (!(n >= 0 && n <= 1)) throw new Error("progress doit être entre 0 et 1"); return n; }
  if (k === "tags") return Array.isArray(v) ? v.map(String) : [];
  if (k === "due") return v ? (isoDate(String(v).slice(0, 10)) ?? (() => { throw new Error("due : date AAAA-MM-JJ attendue"); })()) : null;
  if (k === "stage") { if (!STAGES.includes(v)) throw new Error("stage invalide : " + STAGES.join(", ")); return v; }
  if (k === "priority") { if (v === null || v === "") return null; if (!PRIOS.includes(v)) throw new Error("priority : P1, P2 ou P3"); return v; }
  if (["type", "owner"].includes(k)) return v === "" || v === undefined ? null : v;
  if (k === "title") { const t = String(v ?? "").trim(); if (!t) throw new Error("title obligatoire"); return t; }
  if (TEXTS.includes(k)) return String(v ?? "");
  return v;
}
function rowToIdea(r, withBody) {
  const o = { id: r.id, ref: "IDEE-" + r.ref, title: r.title, stage: r.stage, type: r.type || "", priority: r.priority || "", owner: r.owner || "",
    tags: r.tags || [], pitch: r.pitch, problem: r.problem, target: r.target, value: r.value, business: r.business, nextStep: r.next_step,
    due: r.due ? fmtDate(r.due) : "", valeur: r.valeur, effort: r.effort, confiance: r.confiance, progress: Number(r.progress),
    notionUrl: r.notion_url || "", created: r.created_at.toISOString(), updated: r.updated_at.toISOString() };
  if (withBody) o.body = r.body_md;
  return o;
}
const fmtDate = d => String(d).slice(0, 10);

async function syncChildren(client, id, md) {
  const b = parseBody(md);
  await client.query("DELETE FROM tasks WHERE idea_id=$1", [id]);
  await client.query("DELETE FROM journal WHERE idea_id=$1", [id]);
  for (const [i, t] of b.tasks.entries())
    await client.query("INSERT INTO tasks(idea_id,position,text,done,due) VALUES($1,$2,$3,$4,$5)", [id, i, t.text, t.done, isoDate(t.due)]);
  for (const [i, j] of b.journal.entries())
    await client.query("INSERT INTO journal(idea_id,position,entry_date,text) VALUES($1,$2,$3,$4)", [id, i, isoDate(j.date), j.text]);
  return b.tasks.length ? Math.round(b.tasks.filter(t => t.done).length / b.tasks.length * 100) / 100 : null;
}
async function tx(fn) {
  const c = await pool.connect();
  try { await c.query("BEGIN"); const r = await fn(c); await c.query("COMMIT"); return r; }
  catch (e) { await c.query("ROLLBACK").catch(() => {}); throw e; }
  finally { c.release(); }
}
async function getOne(c, id, withBody = true) {
  const { rows } = await c.query("SELECT * FROM ideas WHERE id::text=$1 OR ('IDEE-'||ref)=$1 OR ref::text=$1", [String(id)]);
  if (!rows[0]) throw new Error("Fiche introuvable : " + id);
  return rowToIdea(rows[0], withBody);
}
function defaultBody(notes, tasks, journalText) {
  return buildBody({ pre: [], order: ["notes", "plan", "journal"], raw: {}, notes: notes || "",
    tasks: (tasks || []).map(t => typeof t === "string" ? { done: false, text: t, due: "" } : { done: !!t.done, text: String(t.text || ""), due: t.due || "" }),
    journal: journalText ? [{ date: new Date().toISOString().slice(0, 10), text: journalText }] : [], planExtra: [], journalExtra: [] });
}

