/* ---------------- JSON-RPC / Streamable HTTP ---------------- */
const INSTRUCTIONS = "Base PostgreSQL de l'Atelier SAPHYRA (portefeuille d'idées). Corps de fiche en markdown : ## Notes, ## Plan d'action (- [ ] tâche <date start=\"AAAA-MM-JJ\" />), ## Journal (- **AAAA-MM-JJ** — texte).";
async function handle(msg) {
  const { id, method, params = {} } = msg || {};
  if (id === undefined || id === null) return null; // notification
  const ok = result => ({ jsonrpc: "2.0", id, result });
  const err = (code, message) => ({ jsonrpc: "2.0", id, error: { code, message } });
  switch (method) {
    case "initialize": return ok({ protocolVersion: params.protocolVersion || "2025-06-18", capabilities: { tools: { listChanged: false } },
      serverInfo: { name: "saphyra-db", title: "Atelier SAPHYRA (base VPS)", version: "1.0.0" }, instructions: INSTRUCTIONS });
    case "ping": return ok({});
    case "tools/list": return ok({ tools: TOOLS.map(({ run, ...t }) => t) });
    case "tools/call": {
      const t = TOOLS.find(x => x.name === params.name);
      if (!t) return err(-32602, "Outil inconnu : " + params.name);
      try {
        const res = await t.run(params.arguments || {});
        return ok({ content: [{ type: "text", text: JSON.stringify(res) }], structuredContent: res });
      } catch (e) {
        console.error(`[${params.name}]`, e.message);
        return ok({ content: [{ type: "text", text: "Erreur : " + e.message }], isError: true });
      }
    }
    case "resources/list": return ok({ resources: [] });
    case "prompts/list": return ok({ prompts: [] });
    default: return err(-32601, "Méthode non prise en charge : " + method);
  }
}

function send(res, code, body, headers = {}) {
  res.writeHead(code, { "Content-Type": "application/json", "Cache-Control": "no-store", ...headers });
  res.end(body === undefined ? "" : JSON.stringify(body));
}
